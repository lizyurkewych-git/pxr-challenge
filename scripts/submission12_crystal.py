CRYSTAL_LIGANDS = "data/pxr_crystal_ligands.csv"  # generated by fetch_crystal_ligands.py


# ------------------------------------------------------------------
# PXR crystal ligand Tanimoto features
# ------------------------------------------------------------------

def build_crystal_features(smiles: list[str]) -> np.ndarray:
    """ECFP4 Tanimoto similarity to the 56 PXR co-crystal ligands.

    Returns an (n, 5) float32 array: max_sim, mean_sim, std_sim, top2_sim, top3_sim.
    """
    import pandas as pd
    from rdkit import Chem, DataStructs
    from rdkit.Chem import rdFingerprintGenerator

    gen = rdFingerprintGenerator.GetMorganGenerator(radius=2, fpSize=2048)
    crystal_df = pd.read_csv(CRYSTAL_LIGANDS)
    crystal_fps = [
        gen.GetFingerprint(mol)
        for smi in crystal_df["smiles"]
        if (mol := Chem.MolFromSmiles(smi)) is not None
    ]
    logger.info(f"Crystal ligands: {len(crystal_fps)} valid fingerprints loaded")

    features = []
    for smi in smiles:
        mol = Chem.MolFromSmiles(smi)
        if mol is None:
            features.append(np.zeros(5, dtype=np.float32))
            continue
        sims = sorted(
            DataStructs.BulkTanimotoSimilarity(gen.GetFingerprint(mol), crystal_fps),
            reverse=True,
        )
        features.append(np.array([
            sims[0]              if len(sims) > 0 else 0.0,
            float(np.mean(sims)) if len(sims) > 0 else 0.0,
            float(np.std(sims))  if len(sims) > 1 else 0.0,
            sims[1]              if len(sims) > 1 else 0.0,
            sims[2]              if len(sims) > 2 else 0.0,
        ], dtype=np.float32))

    return np.array(features, dtype=np.float32)


# ------------------------------------------------------------------
# TabPFN backed by CheMeleon PCA + extra tabular features
# ------------------------------------------------------------------

class TabPFNAugmented:
    """TabPFN v2 backed by frozen CheMeleon embeddings + extra features.

    CheMeleon (2048-dim) is PCA-compressed to 200 components. The extra
    features (crystal Tanimoto, 5-dim) are standardized and appended,
    giving the model access to biology-anchored structural signal alongside
    the learned chemical-language representation.

    CheMeleon inference runs on CPU (fast feature extractor, ~30 s/fold).
    TabPFN forward pass runs on DEVICE (GPU recommended, ~5-10 s/fold vs
    3-7 min on CPU).
    """

    def __init__(self, n_components=200, n_estimators=32,
                 device="cuda", cache_dir="data/embed_cache", random_state=42):
        self.n_components  = n_components
        self.n_estimators  = n_estimators
        self.device        = device
        self.cache_dir     = cache_dir
        self.random_state  = random_state

    def _embed(self, smiles):
        from src.models.foundation_embeddings import CheMeleonEmbedder
        return CheMeleonEmbedder(device="cpu", cache_dir=self.cache_dir).transform(smiles)

    def fit(self, smiles, y, extra_features=None):
        from sklearn.decomposition import PCA
        from sklearn.preprocessing import StandardScaler
        from tabpfn import TabPFNRegressor

        X_raw = self._embed(smiles)
        self._scaler = StandardScaler()
        X_sc = self._scaler.fit_transform(X_raw)
        n_comp = min(self.n_components, X_sc.shape[0] - 1, X_sc.shape[1])
        self._pca = PCA(n_components=n_comp, random_state=self.random_state)
        X_pca = self._pca.fit_transform(X_sc)

        if extra_features is not None:
            self._extra_scaler = StandardScaler()
            X_extra = self._extra_scaler.fit_transform(extra_features.astype(np.float64))
            X_final = np.hstack([X_pca, X_extra])
        else:
            self._extra_scaler = None
            X_final = X_pca

        self._tabpfn = TabPFNRegressor(
            n_estimators=self.n_estimators, device=self.device,
            random_state=self.random_state, ignore_pretraining_limits=True,
        )
        self._tabpfn.fit(X_final, np.asarray(y, dtype=np.float32))
        logger.info(f"TabPFNAugmented.fit: {X_final.shape[1]} total features")
        return self

    def predict(self, smiles, extra_features=None):
        X_pca = self._pca.transform(self._scaler.transform(self._embed(smiles)))
        if extra_features is not None and self._extra_scaler is not None:
            X_extra = self._extra_scaler.transform(extra_features.astype(np.float64))
            X_final = np.hstack([X_pca, X_extra])
        else:
            X_final = X_pca
        return self._tabpfn.predict(X_final).astype(np.float32)


