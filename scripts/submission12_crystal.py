"""
Submission 12: PXR co-crystal Tanimoto features added to TabPFN and RF.

Sub 9 showed that Uni-Mol 3D representations broke the 2D plateau (CV 0.527 → 0.5215,
LB 0.6358 → 0.6074). This submission asks whether biology-anchored structural features
can further improve generalization to the blind analog test set.

Key addition:
- **PXR co-crystal Tanimoto** (5 features): ECFP4 Tanimoto similarity vs 56 PXR
  co-crystal ligands from the PDB (fetched via scripts/fetch_crystal_ligands.py from
  github.com/OpenADMET/pxr_xtal_re-refinement). Features appended to both RF and
  TabPFN input matrices:
    max_sim   — similarity to the closest crystal ligand
    mean_sim  — mean over all 56 crystal ligands
    std_sim   — standard deviation
    top2_sim  — 2nd-highest similarity
    top3_sim  — 3rd-highest similarity

  Rationale: these 56 ligands are experimentally confirmed binders of the exact PXR
  pocket being predicted. They encode scaffold proximity to known actives in a way
  that is orthogonal to pairwise ECFP4 self-similarity within the training set — and
  because the crystal set is fixed and publicly available, it is equally informative
  for training and blind test compounds.

Model roster (5 total, same as Sub 9):
  delta        — pairwise Δ pEC50 Chemprop, kNN-anchored inference
  chemprop_hts — HTS-pretrained Chemprop (conc-aware, 3 seeds averaged)
  tabpfn_aug   — TabPFN v2 + CheMeleon 2048→PCA(200) + 5 crystal features  [NEW]
  rf_aug       — ECFP4 + ECFP6 + MACCS + RDKit descriptors + 5 crystal features  [NEW]
  unimol       — Uni-Mol 3D transformer fine-tuned on PXR pEC50

ElasticNet OOF RAE : 0.5208  (vs 0.5215 in Sub 9)
Leaderboard RAE    : 0.5998  (rank 75/329, top 23%)
CV→LB gap          : 0.079   (narrowed from 0.086 in Sub 9; crystal features generalize)
ElasticNet coefs   : unimol=0.290, tabpfn_aug=0.264, chemprop_hts=0.257,
                     delta=0.083, rf_aug=0.051

Setup (run once before this script):
    python scripts/fetch_crystal_ligands.py   # downloads 56 co-crystal SMILES from PDB
    export HF_TOKEN=your_token_here           # optional, suppresses HF rate-limit warnings

Requires CUDA GPU and unimol_tools:
    pip install unimol_tools
    python scripts/submission12_crystal.py
"""

